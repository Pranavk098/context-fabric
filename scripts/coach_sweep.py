"""Offline sweep of the coach's fire-turn and cost thresholds: precision and recall each.

Read-only replay over ``<root>/*/<session>.jsonl`` with the same reader as
``scripts/bound_coach_replay.py``. A session fires at a setting when it reaches the fire
turn having spent at least the cost threshold in cache-read dollars, the figure the nudge
quotes. The target set is the top 10% of sessions by the same measure, so precision is
the share of fired sessions in that set and recall the share of it that fired.

Aggregates only: counts and shares, never a path, prompt, command or transcript text
(R6). Every row is *measured* on one machine's replay. The tester setting is picked from
this table and frozen in the W0 decisions file before tester week; this script never sees
tester data, so it cannot retune on it.
"""

from __future__ import annotations

import argparse
import math
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

_REPO = Path(__file__).resolve().parents[1]
_SCRIPTS = Path(__file__).resolve().parent
for _path in (_REPO, _SCRIPTS):
    if str(_path) not in sys.path:
        sys.path.insert(0, str(_path))

from bound_coach_replay import scan_coach  # noqa: E402

from cfxd.brief_receipts import _iter_jsonl  # noqa: E402
from cfxd.coach import _turn_cost  # noqa: E402
from cfxd.routing import _DEFAULT_PRICES, _load_prices  # noqa: E402

FIRE_TURNS = (10, 15, 20, 25, 30, 40)
COSTS = (0.25, 0.5, 1.0, 2.0, 4.0, 8.0)
_TOP_SHARE = 0.10


def collect(root: Path) -> list[dict[str, Any]]:
    """One (context, model) pair per assistant turn end, per session; duplicates skipped."""
    prices = _load_prices(_DEFAULT_PRICES)
    sessions: list[dict[str, Any]] = []
    seen: set[str] = set()
    for path in sorted(root.glob("*/*.jsonl")):
        if path.stem in seen:
            continue
        seen.add(path.stem)
        objs = list(_iter_jsonl(path))
        if objs:
            sessions.append({"session": path.stem, "turns": scan_coach(objs, prices)["turns"]})
    return sessions


def session_cost(turns: Sequence[tuple[int, str | None]]) -> float:
    total = 0.0
    for context, model in turns:
        total += _turn_cost(model, context) or 0.0
    return total


def first_fire(turns: Sequence[tuple[int, str | None]], fire_turn: int, cost: float) -> int | None:
    """Turn the rule fires at, or None: turn >= ``fire_turn`` and spend so far >= ``cost``."""
    total = 0.0
    for number, (context, model) in enumerate(turns, 1):
        total += _turn_cost(model, context) or 0.0
        if number >= fire_turn and total >= cost:
            return number
    return None


def sweep(
    sessions: Sequence[dict[str, Any]],
    fire_turns: Sequence[int] = FIRE_TURNS,
    costs: Sequence[float] = COSTS,
) -> dict[str, Any]:
    """Precision and recall for every (fire turn, cost) pair, against the top 10% by cost."""
    measured = [
        {"session": s["session"], "turns": s["turns"], "cost": session_cost(s["turns"])}
        for s in sessions
    ]
    ranked = sorted((s for s in measured if s["cost"] > 0), key=lambda s: s["cost"], reverse=True)
    top_k = max(1, math.ceil(_TOP_SHARE * len(ranked))) if ranked else 0
    top = {s["session"] for s in ranked[:top_k]}
    rows: list[dict[str, Any]] = []
    for fire_turn in fire_turns:
        for cost in costs:
            fired = hits = 0
            for session in ranked:
                if first_fire(session["turns"], fire_turn, cost) is None:
                    continue
                fired += 1
                hits += session["session"] in top
            precision = hits / fired if fired else None
            recall = hits / top_k if top_k else None
            rows.append(
                {
                    "fire_turn": fire_turn,
                    "cost_usd": cost,
                    "fired": fired,
                    "hits": hits,
                    "precision": precision,
                    "recall": recall,
                    "f1": (
                        2 * precision * recall / (precision + recall)
                        if precision and recall
                        else None
                    ),
                }
            )
    return {"rows": rows, "top_k": top_k, "n_priced": len(ranked), "n_sessions": len(measured)}


def render(data: dict[str, Any]) -> str:
    out: list[str] = []
    w = out.append
    w("# Coach threshold sweep (*measured* on replay)")
    w("")
    w("Generated by `scripts/coach_sweep.py`. Aggregates only: no paths, prompts, commands")
    w("or transcript text. Cost is the cache-read dollars the nudge itself quotes, summed")
    w("over the session; it is an API list-price equivalent, not a bill.")
    w("")
    w(f"- Sessions: {data['n_sessions']} (with a priced turn: {data['n_priced']})")
    w(f"- Target set: the top 10% of priced sessions by cost ({data['top_k']})")
    w("")
    w("| fire turn | cost | fired | hits | precision | recall | F1 |")
    w("|---|---|---|---|---|---|---|")
    for row in data["rows"]:
        w(
            f"| {row['fire_turn']} | {_usd(row['cost_usd'])} | {row['fired']} | "
            f"{row['hits']} | {_pct(row['precision'])} | {_pct(row['recall'])} | "
            f"{_pct(row['f1'])} |"
        )
    w("")
    best = max(
        (row for row in data["rows"] if row["f1"] is not None),
        key=lambda row: (row["f1"], -row["fire_turn"], -row["cost_usd"]),
        default=None,
    )
    if best is not None:
        w(
            f"Highest F1 on this replay: fire turn {best['fire_turn']} at "
            f"{_usd(best['cost_usd'])} - precision {_pct(best['precision'])}, "
            f"recall {_pct(best['recall'])}."
        )
    else:
        w("No setting fired on this replay; nothing to recommend.")
    w("")
    w("## Caveats")
    w("")
    w(
        "- *Measured* on one person's transcripts on one machine. It is a replay, not "
        "tester data; the tester setting is frozen from this table before tester week and "
        "is not retuned afterwards."
    )
    w(
        "- The top 10% is a rank cut, so ties at the cutoff are not split, and a session "
        "that never reaches the fire turn can never be recalled (recall ceiling)."
    )
    w(
        "- A session counts once, at its first fire. The shipped cooldown between two "
        "nudges is not modelled here; it changes exposure, not whether a session fires."
    )
    w("")
    return "\n".join(out)


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}%"


def _usd(value: float) -> str:
    return f"${value:,.2f}"


def _floats(text: str) -> list[float]:
    return [float(part) for part in text.split(",") if part.strip()]


def _ints(text: str) -> list[int]:
    return [int(part) for part in text.split(",") if part.strip()]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Coach fire-turn and cost threshold sweep")
    parser.add_argument("--root", type=Path, default=Path.home() / ".claude" / "projects")
    parser.add_argument("--fire-turns", type=_ints, default=list(FIRE_TURNS))
    parser.add_argument("--costs", type=_floats, default=list(COSTS))
    args = parser.parse_args(argv)
    text = render(sweep(collect(args.root), args.fire_turns, args.costs))
    sys.stdout.write(text + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
